/**
 * Explains a refusal in the reader's language: the reason's words, how long to wait, or a general apology.
 *
 * @example
 * explainRefusal({ reason: "identifier-taken" }, "en"); // "That identifier is taken. Try another."
 */
export function explainRefusal(refusal: { reason: string; retryAfterSeconds?: number }, locale: AccountLocale): string {
  if (refusal.reason === "rate-limit") {
    const minutes = Math.max(1, Math.ceil((refusal.retryAfterSeconds ?? 60) / 60));
    const unit = minutes === 1 ? ACCOUNT_WORDS.error.minute : ACCOUNT_WORDS.error.minutes;
    return `${say(ACCOUNT_WORDS.error.wait, locale)} ${minutes} ${say(unit, locale)}.`;
  }
  return say(REASONS[refusal.reason] ?? ACCOUNT_WORDS.error.generic, locale);
}
